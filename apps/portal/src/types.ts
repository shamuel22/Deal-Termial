/** Formas de respuesta de la API usadas por varias páginas (subconjunto de los tipos de core). */
export interface Address {
  line1: string;
  line2?: string;
  city: string;
  state: string;
  postalCode: string;
}

export interface QuoteView {
  id: string;
  version: number;
  kind: 'quote' | 'counter';
  author: 'buyer' | 'supplier';
  status: string;
  autoGenerated: boolean;
  product: { name?: string; sku?: string; attributes?: Record<string, unknown> };
  quantity: number;
  unit: string;
  listUnitPrice: string;
  unitPrice: string;
  subtotal: string;
  discountTotal: string;
  shipping: string;
  tax: string;
  total: string;
  currency: string;
  deliveryAddress: Address;
  deliverBy: string;
  expiresAt: string;
  message: string | null;
  createdAt: string;
}

export interface NegotiationView {
  id: string;
  requestId: string;
  status: string;
  buyer: { orgId: string; name: string };
  supplier: { orgId: string; name: string };
  quotes: QuoteView[];
  authorizationCheck?: {
    authorizationId: string;
    violations: Array<{ code: string; message: string }>;
  } | null;
}

export interface OrderView {
  id: string;
  status: string;
  paymentMode: 'manual' | 'delegated';
  deliveryStatus: string;
  buyer: { orgId: string; name: string };
  supplier: { orgId: string; name: string };
  total: string;
  currency: string;
  terms: {
    quoteId: string;
    quoteVersion: number;
    product: { name?: string; sku?: string; attributes?: Record<string, unknown> };
    quantity: number;
    unit: string;
    listUnitPrice: string;
    unitPrice: string;
    subtotal: string;
    discountTotal: string;
    shipping: string;
    tax: string;
    total: string;
    deliveryAddress: Address;
    deliverBy: string;
  };
  acceptedBy: { agentId: string | null; userId: string | null; level: string | null };
  authorization: { id: string; version: number } | null;
  stockReservation: { status: string; expiresAt: string } | null;
  budgetReservation: { status: string; amount: string } | null;
  payment: {
    status: string;
    paypalOrderId: string | null;
    paypalCaptureId: string | null;
    updatedAt: string;
  } | null;
  incident: string | null;
  acceptedAt: string;
  paidAt: string | null;
  cancelledAt: string | null;
}

export interface PaymentSummary {
  status: string;
  approveUrl?: string | null;
  reason?: string;
  message?: string;
}

export interface ActivityItem {
  id: string;
  at: string;
  actor: { type: string; id: string | null; name: string | null };
  action: string;
  resourceType: string;
  resourceId: string | null;
  outcome: string;
  details: unknown;
}
