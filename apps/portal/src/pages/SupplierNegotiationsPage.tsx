import { useState, type FormEvent } from 'react';
import { post } from '../api';
import { Check, Field, MoneyField, Table, numberFrom, textFrom } from '../components/forms';
import { Badge, Empty, ErrorBox, Loading, Money, PageHeader, formatDate } from '../components/ui';
import { useAction, useResource } from '../hooks';
import { useSession } from '../session';

interface Quote {
  id: string;
  version: number;
  author: 'buyer' | 'supplier';
  kind: 'quote' | 'counter';
  quantity: number;
  unitPrice: string;
  total: string;
  currency: string;
  deliverBy: string;
  status: string;
  autoGenerated: boolean;
  ruleTrace?: unknown;
  shipping: string;
  tax: string;
  discountTotal: string;
  expiresAt: string;
  message: string | null;
  deliveryAddress: {
    line1: string;
    line2?: string;
    city: string;
    state: string;
    postalCode: string;
    country: string;
  };
}
interface Negotiation {
  id: string;
  buyer: { orgId: string; name: string };
  status: string;
  latestVersion: number;
  quotes: Quote[];
}
interface QuoteTerms {
  quantity: number;
  unitPrice: string;
  waiveShipping: boolean;
  deliverBy: string;
  message: string;
}
type ResponseBody =
  QuoteTerms | { action: 'accept' | 'reject' } | { action: 'counter'; terms: QuoteTerms };
export default function SupplierNegotiationsPage() {
  const { orgPath } = useSession();
  const base = orgPath('/supplier/negotiations');
  return <Negotiations key={base} base={base} />;
}
function Negotiations({ base }: { base: string }) {
  const negotiations = useResource<Negotiation[]>(`${base}?status=all`);
  const list = [...(negotiations.data ?? [])].sort(
    (a, b) => Number(b.status === 'awaiting_supplier') - Number(a.status === 'awaiting_supplier'),
  );
  return (
    <>
      <PageHeader
        title="Sales negotiations"
        subtitle="Negotiations awaiting your response as supplier appear first."
      />
      <ErrorBox error={negotiations.error} />
      {negotiations.loading && <Loading />}
      {negotiations.data?.length === 0 && <Empty>No sales negotiations.</Empty>}
      {list.map((n) => (
        <NegotiationCard key={n.id} negotiation={n} base={base} reload={negotiations.reload} />
      ))}
    </>
  );
}
function NegotiationCard({
  negotiation: n,
  base,
  reload,
}: {
  negotiation: Negotiation;
  base: string;
  reload: () => void;
}) {
  const [message, setMessage] = useState('');
  const action = useAction((endpoint: string, body: ResponseBody) =>
    post<Negotiation>(`${base}/${n.id}/${endpoint}`, body),
  );
  const latest = n.quotes.find((q) => q.version === n.latestVersion);
  const canRespond =
    n.status === 'awaiting_supplier' &&
    latest?.author === 'buyer' &&
    latest.kind === 'counter' &&
    latest.status === 'proposed';
  const canQuote = n.status === 'awaiting_supplier' && n.quotes.length === 0;
  async function respond(kind: 'accept' | 'reject') {
    if (
      !window.confirm(
        kind === 'accept'
          ? 'Accept the buyer’s latest counteroffer with the amounts and terms shown?'
          : 'Reject this counteroffer and close the negotiation?',
      )
    )
      return;
    setMessage('');
    if (await action.run('respond', { action: kind })) {
      reload();
      setMessage('Response recorded.');
    }
  }
  async function submit(e: FormEvent<HTMLFormElement>) {
    e.preventDefault();
    const form = new FormData(e.currentTarget);
    const terms: QuoteTerms = {
      quantity: numberFrom(form, 'quantity'),
      unitPrice: textFrom(form, 'unitPrice'),
      waiveShipping: form.has('waiveShipping'),
      deliverBy: textFrom(form, 'deliverBy'),
      message: textFrom(form, 'message'),
    };
    setMessage('');
    if (
      await action.run(
        canQuote ? 'quote' : 'respond',
        canQuote ? terms : { action: 'counter', terms },
      )
    ) {
      reload();
      setMessage('Quote submitted.');
    }
  }
  return (
    <section className="card">
      <h2>
        {n.buyer.name || 'Buyer organization'} · <Badge value={n.status} />
      </h2>
      <p className="muted">Negotiation {n.id}</p>
      {message && (
        <p className="alert ok" role="status">
          {message}
        </p>
      )}
      {n.quotes.length ? (
        <Table title="Negotiation version history">
          <thead>
            <tr>
              <th>Version</th>
              <th>Author</th>
              <th>Type</th>
              <th>Quantity</th>
              <th>Unit price</th>
              <th>Total</th>
              <th>Delivery</th>
              <th>Status</th>
              <th>Automatic</th>
              <th>Details and rules</th>
            </tr>
          </thead>
          <tbody>
            {[...n.quotes]
              .sort((a, b) => a.version - b.version)
              .map((q) => (
                <tr key={q.id}>
                  <td className="num">{q.version}</td>
                  <td>{q.author === 'buyer' ? 'Buyer' : 'Supplier'}</td>
                  <td>{q.kind === 'counter' ? 'Counteroffer' : 'Quote'}</td>
                  <td className="num">{q.quantity}</td>
                  <td>
                    <Money value={q.unitPrice} currency={q.currency} />
                  </td>
                  <td>
                    <Money value={q.total} currency={q.currency} />
                  </td>
                  <td>{formatDate(q.deliverBy)}</td>
                  <td>
                    <Badge value={q.status} />
                  </td>
                  <td>{q.autoGenerated ? 'Yes' : 'No'}</td>
                  <td>
                    <details>
                      <summary>View terms and rules</summary>
                      <dl className="kv">
                        <dt>Shipping</dt>
                        <dd>
                          <Money value={q.shipping} currency={q.currency} />
                        </dd>
                        <dt>Taxes</dt>
                        <dd>
                          <Money value={q.tax} currency={q.currency} />
                        </dd>
                        <dt>Discount</dt>
                        <dd>
                          <Money value={q.discountTotal} currency={q.currency} />
                        </dd>
                        <dt>Expires</dt>
                        <dd>{formatDate(q.expiresAt, true)}</dd>
                      </dl>
                      <p>
                        {q.deliveryAddress.line1}
                        {q.deliveryAddress.line2 && `, ${q.deliveryAddress.line2}`},{' '}
                        {q.deliveryAddress.city}, {q.deliveryAddress.state}{' '}
                        {q.deliveryAddress.postalCode}, United States
                      </p>
                      {q.message && <p>{q.message}</p>}
                      <h3>Private rule trace</h3>
                      {q.ruleTrace ? (
                        <pre className="portal-json">{JSON.stringify(q.ruleTrace, null, 2)}</pre>
                      ) : (
                        <p className="muted">No rule trace for this version.</p>
                      )}
                    </details>
                  </td>
                </tr>
              ))}
          </tbody>
        </Table>
      ) : (
        <p>The buyer is waiting for your first quote.</p>
      )}
      <ErrorBox error={action.error} />
      {canRespond && (
        <div className="actions">
          <button
            className="primary"
            disabled={action.pending}
            onClick={() => void respond('accept')}
          >
            Accept counteroffer
          </button>
          <button
            className="danger"
            disabled={action.pending}
            onClick={() => void respond('reject')}
          >
            Reject counteroffer
          </button>
        </div>
      )}
      {(canRespond || canQuote) && (
        <form key={n.latestVersion} className="stack" onSubmit={submit}>
          <h3>{canQuote ? 'Create quote' : 'Create counteroffer'}</h3>
          <p className="muted">
            Tax and shipping are calculated using the offer’s terms. Exceptions to your rules
            granted from the portal are recorded.
          </p>
          <fieldset className="stack" disabled={action.pending}>
            <div className="row">
              <Field
                title="Quantity (units)"
                name="quantity"
                type="number"
                min="1"
                step="1"
                required
                defaultValue={latest?.quantity ?? ''}
              />
              <MoneyField
                title="Unit price (USD)"
                precision={4}
                name="unitPrice"
                defaultValue={latest?.unitPrice ?? ''}
              />
              <Field
                title="Deliver by"
                name="deliverBy"
                type="date"
                required
                defaultValue={latest?.deliverBy ?? ''}
              />
            </div>
            <Check
              title="Waive shipping"
              name="waiveShipping"
              defaultChecked={latest?.shipping === '0.00'}
            />
            <label>
              Message (optional)
              <textarea name="message" rows={2} maxLength={1000} />
            </label>
            <button className="primary">
              {action.pending ? 'Sending…' : canQuote ? 'Submit quote' : 'Submit counteroffer'}
            </button>
          </fieldset>
        </form>
      )}
    </section>
  );
}
