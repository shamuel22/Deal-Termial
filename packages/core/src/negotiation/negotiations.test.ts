let h: DbHandle;
const NOW = new Date('2026-10-20T12:00:00Z');

beforeAll(async () => {
  h = await createTestDatabase();
});

afterAll(async () => {
  await h?.close();
});

async function expectCode(p: Promise<unknown>, code: ErrorCode) {
  const e = await p.then(
    () => null,
    (x: unknown) => x,
  );
  expect(e, `se esperaba ${code}`).toBeInstanceOf(DomainError);
  expect((e as DomainError).code).toBe(code);
}

// Oferta A de la demo (kraft 16 oz): lista 0.24 para 250+, envío 5.00, 8.25 %, piso 0.22.
const OFFER_A: OfferFixture = {
  tiers: [
    { minQty: 50, unitPrice: '0.3100' },
    { minQty: 250, unitPrice: '0.2400' },
  ],
  shippingFlat: '5.00',
  taxRate: '0.0825',
  leadTimeDays: 2,
  rules: {
    maxDiscount: '0.1000',
    floorUnitPrice: '0.2200',
    minQtyForDiscount: 250,
    minLeadTimeDays: 1,
  },
};

interface Scene {
  buyer: UserActor;
  agent: AgentActor;
  supplier: UserActor;
  offerId: string;
  requestId: string;
  authorizationId: string;
}

async function scene(
  level: BuyerLevel = 'full_autonomy',
  offer: OfferFixture = OFFER_A,
): Promise<Scene> {
  const buyer = await newCompany(h.db, 'Taqueria');
  const agent = await newAgent(h.db, buyer, level);
  const supplier = await newCompany(h.db, 'EcoPack');
  const { offerId } = await newOffer(h.db, supplier.orgId, offer);
  const auth = await createAuthorization(
    h.db,
    buyer,
    { agentId: agent.agentId, terms: demoTerms() },
    NOW,
  );
  const request = await createRequest(h.db, agent, { authorizationId: auth.id }, NOW);
  return { buyer, agent, supplier, offerId, requestId: request.id, authorizationId: auth.id };
}

describe('negociación automática por reglas (caso de uso)', () => {
  it('cotización a precio de lista, contraoferta y ajuste dentro del presupuesto', async () => {
    const s = await scene();
    const opened = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    expect(opened.status).toBe('awaiting_buyer');
    expect(opened.quotes).toHaveLength(1);
    expect(opened.quotes[0]).toMatchObject({
      kind: 'quote',
      author: 'supplier',
      autoGenerated: true,
      unitPrice: '0.2400',
      total: '83.35',
      deliverBy: '2026-10-22',
    });
    // La comprobación informativa avisa de que la lista supera los US$80 autorizados.
    expect(opened.authorizationCheck?.violations.map((v) => v.code)).toEqual(['BUDGET_EXCEEDED']);

    const countered = await counterQuote(h.db, s.agent, opened.id, { unitPrice: '0.2000' }, NOW);
    expect(countered.status).toBe('awaiting_buyer');
    expect(countered.quotes.map((q) => [q.version, q.kind, q.author, q.status])).toEqual([
      [1, 'quote', 'supplier', 'superseded'],
      [2, 'counter', 'buyer', 'superseded'],
      [3, 'quote', 'supplier', 'proposed'],
    ]);
    expect(countered.quotes[2]).toMatchObject({
      unitPrice: '0.2200',
      discountTotal: '6.00',
      total: '76.86',
    });
    expect(countered.authorizationCheck?.violations).toEqual([]);
  });

  it('el proveedor acepta una contrapropuesta dentro de sus reglas', async () => {
    const s = await scene();
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    const out = await counterQuote(h.db, s.agent, n.id, { unitPrice: '0.2250' }, NOW);
    expect(out.quotes.at(-1)).toMatchObject({
      unitPrice: '0.2250',
      message: 'Aceptamos tu propuesta.',
    });
  });

  it('pedir cotización dos veces devuelve la misma negociación', async () => {
    const s = await scene();
    const a = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    const b = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    expect(b.id).toBe(a.id);
    expect(b.quotes).toHaveLength(1);
  });

  it('el comprador nunca ve las reglas ni la traza del proveedor; el proveedor sí', async () => {
    const s = await scene();
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    const buyerView = await counterQuote(h.db, s.agent, n.id, { unitPrice: '0.1000' }, NOW);
    const json = JSON.stringify(buyerView);
    expect(json).not.toMatch(/ruleTrace|piso|permitido|floor/i);

    const supplierView = await getNegotiation(h.db, s.supplier, n.id, NOW);
    expect(JSON.stringify(supplierView.quotes.at(-1)?.ruleTrace)).toContain('0.2200');
  });
});

describe('niveles del comprador (criterios 3 y 4)', () => {
  it('solo búsqueda no puede pedir cotizaciones ni contraofertar', async () => {
    const s = await scene('search_only');
    await expectCode(
      requestQuote(h.db, s.agent, { requestId: s.requestId, offerId: s.offerId }, NOW),
      'LEVEL_INSUFFICIENT',
    );
  });

  it('solo negociación negocia y deja la propuesta final para el dueño', async () => {
    const s = await scene('negotiate');
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    await counterQuote(h.db, s.agent, n.id, { unitPrice: '0.2200' }, NOW);
    const reviewed = await submitForReview(
      h.db,
      s.agent,
      n.id,
      { message: 'Listo para pagar' },
      NOW,
    );
    expect(reviewed.status).toBe('pending_owner_review');

    const notes = await h.db
      .select()
      .from(schema.notifications)
      .where(
        and(
          eq(schema.notifications.orgId, s.buyer.orgId),
          eq(schema.notifications.kind, 'negotiation.pending_owner_review'),
        ),
      );
    expect(notes).toHaveLength(1);
    expect(notes[0]!.body).toContain('76.86');
    // Tras enviarla a revisión, el agente ya no puede seguir modificándola.
    await expectCode(
      counterQuote(h.db, s.agent, n.id, { unitPrice: '0.2300' }, NOW),
      'INVALID_STATE',
    );
  });

  it('no se puede enviar a revisión una cotización vencida', async () => {
    const s = await scene('negotiate');
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    const later = new Date(NOW.getTime() + 49 * 3_600_000);
    await expectCode(submitForReview(h.db, s.agent, n.id, {}, later), 'QUOTE_EXPIRED');
    expect((await getNegotiation(h.db, s.agent, n.id, later)).quotes[0]!.status).toBe('expired');
    expect(await expireQuotes(h.db, later)).toBeGreaterThanOrEqual(1);
  });
});

describe('proveedor sin respuesta automática', () => {
  const manual: OfferFixture = { ...OFFER_A, rules: { ...OFFER_A.rules, autoRespond: false } };

  it('queda pendiente; su agente cotiza solo dentro de sus reglas y el dueño aprueba excepciones', async () => {
    const s = await scene('full_autonomy', manual);
    const seller = await newAgent(h.db, s.supplier, null, ['submit_quotes']);
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    expect(n.status).toBe('awaiting_supplier');
    expect(n.quotes).toEqual([]);

    const pending = await listSupplierNegotiations(h.db, seller, undefined, NOW);
    expect(pending.map((x) => x.id)).toContain(n.id);

    const below = { quantity: 300, unitPrice: '0.2000', deliverBy: '2026-10-22' };
    await expectCode(submitQuote(h.db, seller, n.id, below, NOW), 'OUTSIDE_SUPPLIER_RULES');
    // El dueño del proveedor sí puede aprobar una excepción.
    const exception = await submitQuote(h.db, s.supplier, n.id, below, NOW);
    expect(exception.quotes.at(-1)).toMatchObject({
      unitPrice: '0.2000',
      author: 'supplier',
      autoGenerated: false,
    });
    expect(JSON.stringify(exception.quotes.at(-1)?.ruleTrace)).toContain('Excepción aprobada');
  });

  it('aceptar una contrapropuesta exige accept_terms y respeta las reglas', async () => {
    const s = await scene('full_autonomy', manual);
    const quoter = await newAgent(h.db, s.supplier, null, ['submit_quotes']);
    const closer = await newAgent(h.db, s.supplier, null, ['submit_quotes', 'accept_terms']);
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    await submitQuote(
      h.db,
      quoter,
      n.id,
      { quantity: 300, unitPrice: '0.2400', deliverBy: '2026-10-22' },
      NOW,
    );

    await counterQuote(h.db, s.agent, n.id, { unitPrice: '0.2100' }, NOW);
    await expectCode(
      respondToCounterquote(h.db, quoter, n.id, { action: 'accept' }, NOW),
      'SELLER_SCOPE_MISSING',
    );
    await expectCode(
      respondToCounterquote(h.db, closer, n.id, { action: 'accept' }, NOW),
      'OUTSIDE_SUPPLIER_RULES',
    );

    const countered = await respondToCounterquote(
      h.db,
      closer,
      n.id,
      { action: 'counter', terms: { quantity: 300, unitPrice: '0.2250', deliverBy: '2026-10-22' } },
      NOW,
    );
    expect(countered.quotes.at(-1)).toMatchObject({ unitPrice: '0.2250', status: 'proposed' });

    await counterQuote(h.db, s.agent, n.id, { unitPrice: '0.2200' }, NOW);
    const accepted = await respondToCounterquote(h.db, closer, n.id, { action: 'accept' }, NOW);
    expect(accepted).toMatchObject({ status: 'awaiting_buyer' });
    expect(accepted.quotes.at(-1)).toMatchObject({ unitPrice: '0.2200', total: '76.86' });
  });

  it('rechazar cierra la negociación', async () => {
    const s = await scene('full_autonomy', manual);
    const closer = await newAgent(h.db, s.supplier, null, ['submit_quotes']);
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    await submitQuote(
      h.db,
      closer,
      n.id,
      { quantity: 300, unitPrice: '0.2400', deliverBy: '2026-10-22' },
      NOW,
    );
    await counterQuote(h.db, s.agent, n.id, { unitPrice: '0.1500' }, NOW);
    const closed = await respondToCounterquote(h.db, closer, n.id, { action: 'reject' }, NOW);
    expect(closed.status).toBe('closed');
    expect(closed.quotes.at(-1)!.status).toBe('rejected');
  });
});

describe('aislamiento', () => {
  it('terceros y otros agentes de la misma organización no ven la negociación', async () => {
    const s = await scene();
    const n = await requestQuote(
      h.db,
      s.agent,
      { requestId: s.requestId, offerId: s.offerId },
      NOW,
    );
    const colleague = await newAgent(h.db, s.buyer, 'full_autonomy');
    const stranger = await newCompany(h.db);

    await expectCode(getNegotiation(h.db, colleague, n.id, NOW), 'NOT_FOUND');
    await expectCode(
      counterQuote(h.db, colleague, n.id, { unitPrice: '0.2200' }, NOW),
      'NOT_FOUND',
    );
    await expectCode(getNegotiation(h.db, stranger, n.id, NOW), 'NOT_FOUND');
    await expectCode(
      submitQuote(
        h.db,
        stranger,
        n.id,
        { quantity: 300, unitPrice: '0.2400', deliverBy: '2026-10-22' },
        NOW,
      ),
      'NOT_FOUND',
    );
    expect(await getQuotesForRequest(h.db, colleague, s.requestId, NOW)).toEqual([]);
    expect((await getQuotesForRequest(h.db, s.agent, s.requestId, NOW)).map((x) => x.id)).toEqual([
      n.id,
    ]);
  });

  it('no se puede negociar con una oferta propia ni con una solicitud ajena', async () => {
    const s = await scene();
    const own = await newOffer(h.db, s.buyer.orgId, OFFER_A);
    await expectCode(
      requestQuote(h.db, s.agent, { requestId: s.requestId, offerId: own.offerId }, NOW),
      'NOT_FOUND',
    );
    const other = await newAgent(h.db, s.buyer, 'full_autonomy');
    await expectCode(
      requestQuote(h.db, other, { requestId: s.requestId, offerId: s.offerId }, NOW),
      'NOT_FOUND',
    );
  });
});
