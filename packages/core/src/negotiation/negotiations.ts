/**
 * Negociación entre el agente comprador y el proveedor (brief §5 pasos 4–6, §9, §10).
 * Cada propuesta es una versión inmutable; la nueva reemplaza a la anterior. El proveedor
 * responde con sus reglas aunque su agente no esté conectado.
 */

const unitPriceInput = z.string().refine(isValidUnitPrice, 'Precio unitario con hasta 4 decimales');

export const requestQuoteInput = z.object({
  requestId: z.uuid(),
  offerId: z.uuid(),
  message: z.string().trim().max(1000).optional(),
});
export type RequestQuoteInput = z.input<typeof requestQuoteInput>;

export const counterInput = z.object({
  quantity: z.number().int().positive().optional(),
  unitPrice: unitPriceInput.optional(),
  waiveShipping: z.boolean().optional(),
  deliverBy: isoDate.optional(),
  message: z.string().trim().max(1000).optional(),
});
export type CounterInput = z.input<typeof counterInput>;

export const supplierQuoteInput = z.object({
  quantity: z.number().int().positive(),
  unitPrice: unitPriceInput,
  waiveShipping: z.boolean().default(false),
  deliverBy: isoDate,
  message: z.string().trim().max(1000).optional(),
});
export type SupplierQuoteInput = z.input<typeof supplierQuoteInput>;

export const counterResponseInput = z.discriminatedUnion('action', [
  z.object({ action: z.literal('accept'), message: z.string().trim().max(1000).optional() }),
  z.object({ action: z.literal('reject'), message: z.string().trim().max(1000).optional() }),
  z.object({ action: z.literal('counter'), terms: supplierQuoteInput }),
]);
export type CounterResponseInput = z.input<typeof counterResponseInput>;

const COUNTER_VALIDITY_MS = 48 * 60 * 60 * 1000;

type NegotiationRow = typeof schema.negotiations.$inferSelect;
type QuoteRow = typeof schema.quotes.$inferSelect;

