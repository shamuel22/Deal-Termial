import {
  boolean,
  char,
  date,
  index,
  integer,
  jsonb,
  pgTable,
  text,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core';
import { createdAt, id, money, tstz, unitPrice, updatedAt } from './columns.js';
import { negotiationStatus, quoteKind, quoteStatus, requestStatus } from './enums.js';
import { purchaseAuthorizations } from './authorization.js';
import { offers } from './catalog.js';
import { agents, organizations, users } from './identity.js';

/** Necesidad privada del comprador. Guardarla no contacta a ningún proveedor. */
export const purchaseRequests = pgTable(
  'purchase_requests',
  {
    id: id(),
    buyerOrgId: uuid('buyer_org_id')
      .notNull()
      .references(() => organizations.id),
    agentId: uuid('agent_id').references(() => agents.id),
    createdByUserId: uuid('created_by_user_id').references(() => users.id),
    authorizationId: uuid('authorization_id').references(() => purchaseAuthorizations.id),
    status: requestStatus('status').notNull().default('open'),
    category: text('category').notNull(),
    // Criterios estructurados: atributos obligatorios, cantidad, zona, fecha, presupuesto.
    criteria: jsonb('criteria').notNull(),
    // Preferencias no obligatorias; influyen en la selección pero no sustituyen restricciones.
    preferences: jsonb('preferences'),
    expiresAt: tstz('expires_at'),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [index('purchase_requests_buyer_idx').on(t.buyerOrgId, t.status)],
);

/** Hilo de negociación entre una solicitud del comprador y una oferta de un proveedor. */
export const negotiations = pgTable(
  'negotiations',
  {
    id: id(),
    requestId: uuid('request_id')
      .notNull()
      .references(() => purchaseRequests.id),
    buyerOrgId: uuid('buyer_org_id')
      .notNull()
      .references(() => organizations.id),
    supplierOrgId: uuid('supplier_org_id')
      .notNull()
      .references(() => organizations.id),
    offerId: uuid('offer_id')
      .notNull()
      .references(() => offers.id),
    status: negotiationStatus('status').notNull().default('awaiting_supplier'),
    // Última versión de cotización/contrapropuesta emitida en el hilo.
    latestVersion: integer('latest_version').notNull().default(0),
    createdAt: createdAt(),
    updatedAt: updatedAt(),
  },
  (t) => [
    uniqueIndex('negotiations_request_offer_uq').on(t.requestId, t.offerId),
    index('negotiations_buyer_idx').on(t.buyerOrgId, t.status),
    index('negotiations_supplier_idx').on(t.supplierOrgId, t.status),
  ],
);

/**
 * Cotización (proveedor) o contrapropuesta (comprador), versionada dentro de la negociación.
 * Una nueva versión reemplaza a la anterior. Todos los importes quedan fijados en la fila.
 */
export const quotes = pgTable(
  'quotes',
  {
    id: id(),
    negotiationId: uuid('negotiation_id')
      .notNull()
      .references(() => negotiations.id),
    version: integer('version').notNull(),
    kind: quoteKind('kind').notNull(),
    status: quoteStatus('status').notNull().default('proposed'),
    offerVersion: integer('offer_version').notNull(),
    // Producto y atributos confirmados por el proveedor en el momento de cotizar.
    productSnapshot: jsonb('product_snapshot').notNull(),
    quantity: integer('quantity').notNull(),
    unit: text('unit').notNull(),
    listUnitPrice: unitPrice('list_unit_price').notNull(),
    unitPrice: unitPrice('unit_price').notNull(),
    subtotal: money('subtotal').notNull(),
    discountTotal: money('discount_total').notNull(),
    shipping: money('shipping').notNull(),
    tax: money('tax').notNull(),
    total: money('total').notNull(),
    currency: char('currency', { length: 3 }).notNull().default('USD'),
    deliveryAddress: jsonb('delivery_address').notNull(),
    deliverBy: date('deliver_by').notNull(),
    expiresAt: tstz('expires_at').notNull(),
    // Autor: agente o usuario de la organización que emite esta versión.
    authorOrgId: uuid('author_org_id')
      .notNull()
      .references(() => organizations.id),
    authorAgentId: uuid('author_agent_id').references(() => agents.id),
    authorUserId: uuid('author_user_id').references(() => users.id),
    // true si la generó el motor de reglas del proveedor sin intervención.
    autoGenerated: boolean('auto_generated').notNull().default(false),
    // Explicación determinista de reglas aplicadas (descuento, tramo, límites).
    ruleTrace: jsonb('rule_trace'),
    message: text('message'),
    createdAt: createdAt(),
  },
  (t) => [
    uniqueIndex('quotes_negotiation_version_uq').on(t.negotiationId, t.version),
    index('quotes_status_idx').on(t.status, t.expiresAt),
  ],
);
